/// <reference types="vitest/config" />
import { fileURLToPath } from 'node:url';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { VitePWA } from 'vite-plugin-pwa';

/**
 * Content-Security-Policy for the built app. GitHub Pages can't send HTTP headers,
 * so it goes in a <meta> tag. It allows only this site's own files and blocks every
 * outside connection: even if something ever injected code, it couldn't send data
 * anywhere. Build-only, because Vite's dev server injects inline scripts.
 */
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data: blob:",
  "connect-src 'self'",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');

function contentSecurityPolicy(): Plugin {
  return {
    name: 'content-security-policy',
    apply: 'build',
    transformIndexHtml: () => [
      {
        tag: 'meta',
        attrs: { 'http-equiv': 'Content-Security-Policy', content: CSP },
        injectTo: 'head-prepend',
      },
    ],
  };
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [
    react(),
    contentSecurityPolicy(),
    VitePWA({
      // 'prompt': a new version waits until the user taps "Reload", so an update
      // never interrupts someone halfway through typing an entry.
      registerType: 'prompt',
      // Registration happens in code (UpdatePrompt via virtual:pwa-register/react),
      // which also avoids an inline script that the CSP would block.
      injectRegister: false,
      includeAssets: ['favicon.svg', 'apple-touch-icon.png'],
      manifest: {
        name: 'Money Tracker',
        short_name: 'Money',
        description: 'Private, offline money tracker. Your data stays on your device.',
        lang: 'en',
        start_url: './',
        scope: './',
        display: 'standalone',
        orientation: 'portrait',
        background_color: '#f6f7f9',
        theme_color: '#2563eb',
        icons: [
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png' },
          { src: 'maskable-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      workbox: {
        // Precache the whole app so it opens with no connection at all.
        globPatterns: ['**/*.{js,css,html,svg,png,webmanifest}'],
        navigateFallback: 'index.html',
        cleanupOutdatedCaches: true,
      },
    }),
  ],
  // Relative base so the built app works under any GitHub Pages path
  // (https://<user>.github.io/<repo>/) without hard-coding the repo name.
  // Safe because routing is hash-based (HashRouter), so every page is served from index.html.
  base: './',
  build: {
    // One ~160 KB (gzipped) bundle is fine here: it is downloaded once and then served
    // offline from the service worker, so splitting it buys little. Revisit if it
    // passes ~700 KB unminified.
    chunkSizeWarningLimit: 700,
  },
  test: {
    environment: 'jsdom',
    setupFiles: ['./src/test/setup.ts'],
    css: { modules: { classNameStrategy: 'non-scoped' } },
    alias: {
      // The real module is generated by vite-plugin-pwa at build time; tests use a stub.
      'virtual:pwa-register/react': fileURLToPath(
        new URL('./src/test/pwaRegisterStub.ts', import.meta.url),
      ),
    },
  },
});
